-- Stable, database-generated tracking numbers for orders and direct purchase requests.
CREATE SEQUENCE IF NOT EXISTS public.orders_invoice_number_seq;
CREATE SEQUENCE IF NOT EXISTS public.purchase_requests_request_number_seq;

ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS invoice_number bigint;

UPDATE public.orders
SET invoice_number = nextval('public.orders_invoice_number_seq')
WHERE invoice_number IS NULL;

SELECT setval(
  'public.orders_invoice_number_seq',
  GREATEST(COALESCE((SELECT MAX(invoice_number) FROM public.orders), 0), 1),
  COALESCE((SELECT MAX(invoice_number) FROM public.orders), 0) > 0
);

ALTER TABLE public.orders
  ALTER COLUMN invoice_number SET DEFAULT nextval('public.orders_invoice_number_seq'),
  ALTER COLUMN invoice_number SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS orders_invoice_number_uidx
  ON public.orders (invoice_number);

ALTER TABLE public.purchase_requests
  ADD COLUMN IF NOT EXISTS request_number bigint;

UPDATE public.purchase_requests
SET request_number = nextval('public.purchase_requests_request_number_seq')
WHERE request_number IS NULL;

SELECT setval(
  'public.purchase_requests_request_number_seq',
  GREATEST(COALESCE((SELECT MAX(request_number) FROM public.purchase_requests), 0), 1),
  COALESCE((SELECT MAX(request_number) FROM public.purchase_requests), 0) > 0
);

ALTER TABLE public.purchase_requests
  ALTER COLUMN request_number SET DEFAULT nextval('public.purchase_requests_request_number_seq'),
  ALTER COLUMN request_number SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS purchase_requests_request_number_uidx
  ON public.purchase_requests (request_number);

COMMENT ON COLUMN public.orders.invoice_number IS
  'Unique stable invoice/tracking number generated by the database.';
COMMENT ON COLUMN public.purchase_requests.request_number IS
  'Unique stable tracking number for a multi-product purchase request, generated by the database.';
